-- Активный визит гостя: стол, за которым гость сейчас находится, и когда
-- визит начался. Нужен для отображения у сотрудника ("гость сейчас на
-- месте") и для автозавершения всех визитов при закрытии смены заведения
-- (см. обсуждение с Никитой 11.10.2026 — вариант "вручную + подстраховка по
-- закрытию смены"). NULL означает "визита сейчас нет".
alter table guests
  add column if not exists active_table_number int,
  add column if not exists active_visit_started_at timestamptz;
