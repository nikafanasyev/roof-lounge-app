-- Профиль гостя: регистрация по телефону (без SMS-подтверждения на старте —
-- см. обсуждение с Никитой 11.10.2026), вкусовой профиль (направления +
-- любимые/нелюбимые ароматы) и расширение вызовов со стола. Гостевой
-- сценарий: QR на столе -> /table/:token -> узнали/завели гостя -> (при
-- первой регистрации) вкусовой квиз -> главный экран гостя (ФИО, QR
-- лояльности, бонусы, последний визит, кнопки вызова и чаевых).

alter table guests
  add column if not exists phone text unique,
  add column if not exists birth_date date,
  add column if not exists loyalty_code text unique default upper(substr(encode(gen_random_bytes(4), 'hex'), 1, 6)),
  add column if not exists bonus_points int not null default 0,
  add column if not exists last_visit_at timestamptz,
  add column if not exists taste_directions text[] not null default '{}',
  add column if not exists liked_aroma_ids uuid[] not null default '{}',
  add column if not exists disliked_aroma_ids uuid[] not null default '{}';

-- Справочник ароматов для вкусового квиза гостя — НЕ то же самое, что
-- справочник табака `flavors` (там конкретные позиции бренд+вкус для
-- мастера, см. 0001_init.sql). Тут обобщённые названия ароматов ("малина",
-- "грейпфрут", "сандал") по направлениям, которые гость выбирает сам —
-- и может дописать свой, если в списке нет (custom = true).
create table aroma_tags (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  direction text not null check (direction in (
    'fruit', 'berry', 'dessert', 'herbal', 'spice', 'tea',
    'alcohol', 'perfume', 'drinks', 'gastro', 'non_aromatic'
  )),
  custom boolean not null default false, -- добавлен гостем вручную, если своего аромата не было в списке
  created_at timestamptz not null default now(),
  unique (name)
);
create index aroma_tags_direction_idx on aroma_tags(direction);

-- "Позвать мастера" — отдельный тип вызова от общего "waiter" (официант).
alter table service_calls drop constraint if exists service_calls_type_check;
alter table service_calls add constraint service_calls_type_check check (type in ('waiter', 'bill', 'help', 'master'));
alter table service_calls add column if not exists guest_id uuid references guests(id) on delete set null;

