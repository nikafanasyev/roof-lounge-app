// Текст чек-листов в базе знаний собираем из тех же массивов, что и сам
// экран смены (BAR_OPEN_CHECKLIST и т.д. выше) — чтобы база знаний не
// расходилась с тем, что реально видит сотрудник в чек-листе.
//
// Разметка тела статьи (см. components/KnowledgeBody.tsx):
// "# " — заголовок-разделитель, "## " — заголовок карточки, "- " — пункт списка.
function formatChecklistSection(title: string, items: ChecklistItem[]): string {
  const lines: string[] = [`# ${title}`];
  let lastSection: string | undefined;
  for (const item of items) {
    if (item.section && item.section !== lastSection) {
      lines.push(`## ${item.section}`);
      lastSection = item.section;
    }
    lines.push(`- ${item.label}`);
  }
  return lines.join("\n");
}

