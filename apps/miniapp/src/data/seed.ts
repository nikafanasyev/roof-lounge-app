// Чай — не рецепт с ингредиентами, а гостевое описание, поэтому здесь
// формат карточек без списков: "## Название" + строка-описание.
type TeaEntry = [name: string, description: string];

function formatTeaCollection(title: string, teas: TeaEntry[]): string {
  const lines: string[] = [`# ${title}`];
  for (const [name, description] of teas) {
    lines.push(`## ${name}`);
    lines.push(description);
  }
  return lines.join("\n");
}

