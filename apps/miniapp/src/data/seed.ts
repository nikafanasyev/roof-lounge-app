// Рецепты записаны как [название, "ингредиент 1, ингредиент 2, ..."] и
// рендерятся в базе знаний как отдельная карточка на напиток/блюдо с
// ингредиентами списком (см. formatRecipeCategory ниже и KnowledgeBody.tsx).
type Recipe = [name: string, ingredients: string];

// Обычный split(", ") ломает описания с уточнением в скобках (например,
// "квас/айран 150 мл, горчица отдельно 20" — внутри "основа для окрошки ...
// (картофель отварной, яйцо куриное, ...)" запятые не должны резать пункты) —
// поэтому режем по запятым только вне скобок.
function splitIngredients(ingredients: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const ch of ingredients) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

function formatRecipeCategory(title: string, recipes: Recipe[]): string {
  const lines: string[] = [`# ${title}`];
  for (const [name, ingredients] of recipes) {
    lines.push(`## ${name}`);
    for (const ingredient of splitIngredients(ingredients)) {
      lines.push(`- ${ingredient}`);
    }
  }
  return lines.join("\n");
}

